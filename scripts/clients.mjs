import { spawnSync } from "node:child_process";
import { readFile, writeFile, mkdir, mkdtemp, rm } from "node:fs/promises";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";
import { python, root } from "./config.mjs";

const action = process.argv[2];
if (!["generate", "check"].includes(action))
  throw new Error("GENERATION_ACTION_REQUIRED");
const artifactArgument = process.argv.indexOf("--artifact-root");
const artifactRoot =
  artifactArgument < 0
    ? root
    : path.resolve(process.argv[artifactArgument + 1]);
if (action === "generate" && artifactArgument >= 0)
  throw new Error("GENERATE_ROOT_OVERRIDE_FORBIDDEN");
const scratchRoot = path.join(root, ".local");
await mkdir(scratchRoot, { recursive: true });
const scratch = await mkdtemp(path.join(scratchRoot, "client-check-"));
const kinds = ["public", "staff", "local-ai", "configuration"];
try {
  // Explicit isolated synthetic test settings select the schema factory, never runtime fallback.
  const result = spawnSync(
    python,
    [
      "scripts/export_schema.py",
      "--config",
      "infra/config/test.json",
      "--profile",
      "test",
      "--output",
      scratch,
    ],
    { cwd: root, stdio: "inherit" },
  );
  if (result.status !== 0) throw new Error("OPENAPI_EXPORT_FAILED");
  const generated = new Map();
  for (const kind of kinds) {
    const schemaText = await readFile(
      path.join(scratch, `${kind}.openapi.json`),
      "utf8",
    );
    const ast = await openapiTS(JSON.parse(schemaText), { alphabetize: true });
    const types = `/** Generated by pinned openapi-typescript from actual ${kind} FastAPI OpenAPI. */\n${astToString(ast)}`;
    generated.set(`contracts/generated/${kind}.openapi.json`, schemaText);
    generated.set(`packages/api-client/src/generated/${kind}.ts`, types);
  }
  generated.set(
    "contracts/generated/full.openapi.json",
    await readFile(path.join(scratch, "full.openapi.json"), "utf8"),
  );
  const drift = [];
  for (const [relative, content] of generated) {
    const target = path.join(artifactRoot, relative);
    if (action === "generate") {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, content);
    } else {
      const current = await readFile(target, "utf8");
      if (current !== content) drift.push(relative);
    }
  }
  if (drift.length)
    throw new Error(`GENERATED_CLIENT_DRIFT: ${drift.join(", ")}`);
  if (action === "check" && artifactArgument < 0) {
    const negative = [];
    const fixtureRoot = path.join(scratch, "artifacts");
    for (const [relative, content] of generated) {
      const target = path.join(fixtureRoot, relative);
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, content);
    }
    for (const kind of kinds) {
      for (const extension of ["types", "schema"]) {
        const relative =
          extension === "types"
            ? `packages/api-client/src/generated/${kind}.ts`
            : `contracts/generated/${kind}.openapi.json`;
        const expected = generated.get(relative);
        const stale = path.join(fixtureRoot, relative);
        await writeFile(stale, `${expected}\nSTALE_OUTPUT_PROBE\n`);
        const probe = spawnSync(
          process.execPath,
          ["scripts/clients.mjs", "check", "--artifact-root", fixtureRoot],
          { cwd: root, encoding: "utf8", shell: false },
        );
        if (
          probe.status !== 1 ||
          !probe.stderr.includes(`GENERATED_CLIENT_DRIFT: ${relative}`)
        )
          throw new Error(`STALE_OUTPUT_NOT_REJECTED: ${kind}`);
        negative.push({
          kind,
          artifact: extension,
          deliberately_stale_result: "REJECTED",
          exitCode: probe.status,
          checker: "actual child-process scratch regeneration",
        });
        await writeFile(stale, expected);
      }
    }
    const publicSchema = JSON.parse(
      generated.get("contracts/generated/public.openapi.json"),
    );
    if (
      Object.keys(publicSchema.paths).some(
        (p) => p.startsWith("/staff") || p.startsWith("/ai"),
      ) ||
      JSON.stringify(publicSchema.components).match(
        /AdvisoryAttachment|StaffCapabilities|ApprovedInputManifest|database_secret_env/,
      )
    )
      throw new Error("PUBLIC_SCHEMA_PRIVATE_LEAK");
    await writeFile(
      path.join(scratchRoot, "client-check-results.json"),
      JSON.stringify(
        { drift: [], scratchRegeneration: "PASS", negative },
        null,
        2,
      ) + "\n",
    );
  }
  console.log(
    action === "generate"
      ? "OPENAPI_CLIENTS_GENERATED"
      : "OPENAPI_CLIENTS_CURRENT; PUBLIC/STAFF/AI STALE PROBES REJECTED",
  );
} finally {
  if (path.resolve(scratch).startsWith(path.resolve(scratchRoot) + path.sep))
    await rm(scratch, { recursive: true, force: true });
}
